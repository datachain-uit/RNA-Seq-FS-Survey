def tab_e1_k10(results, out):
    s = rd(results, "e1_summary.csv")
    s = s[s.classifier == "lr_l2"]
    t = rd(results, "e1_tests_vs_random_b0.csv")
    b0 = rd(results, "e1_b0_table.csv").set_index("cohort")
    key = ["cohort", "method", "k"]
    S = s.set_index(key)
    T = t.set_index(key)

    def cell(c, m, k):
        if (c, m, k) not in S.index:
            return "--"
        r = S.loc[(c, m, k)]
        txt = fsd(r["auroc_mean"], r["auroc_sd"])
        marks = ""
        if (c, m, k) in T.index:
            tr = T.loc[(c, m, k)]
            mk = ""
            if bool(tr["beats_random_holm"]):
                mk += "\\dagger"
            if bool(tr["differs_from_b0_holm"]):
                mk += "\\ddagger"
            if mk:
                marks = "$^{" + mk + "}$"
        log("tab:e1_k10", f"{c}/{m}/k={k}", "auroc_mean+-sd", f"{r['auroc_mean']:.3f}+-{r['auroc_sd']:.3f}", "e1_summary.csv", "auroc_mean, auroc_sd")
        return txt + marks

    tex = header("e1_summary.csv (classifier = lr_l2; auroc_mean, auroc_sd); e1_tests_vs_random_b0.csv (beats_random_holm, differs_from_b0_holm); e1_b0_table.csv (AUROC)")
    tex += r"""\begin{table*}[t]
\centering
\scriptsize
\caption{E1 at the central budget $k = 10$: AUROC of LR-L2 (mean $\pm$ SD over 25 patient-level folds; wrappers 15 folds on the three GPL570 cohorts). Reference rows are evaluated at their own panel size. $\dagger$: above random-$k$ after Holm correction (one-sided Nadeau--Bengio test, family = method $\times$ 8 budgets); $\ddagger$: differs from B0 after Holm (two-sided); every $\ddagger$ in this table lies below B0. The last row counts the data-driven methods that beat random-$k$ at $k = 10$.}
\label{tab:e1_k10}
\setlength{\tabcolsep}{4pt}
\renewcommand{\arraystretch}{1.12}
\begin{adjustbox}{max width=\textwidth}
\begin{tabular}{llccccc}
\toprule
\textbf{Family} & \textbf{Method} & \textbf{TCGA} & \textbf{GSE10245} & \textbf{GSE30219} & \textbf{GSE37745} & \textbf{GSE42127} \\
\midrule
"""
    last_fam = None
    for m in DATA_METHODS:
        fam = FAMILY[m]
        famtxt = fam if fam != last_fam else ""
        if fam != last_fam and last_fam is not None:
            tex += "\\addlinespace[2pt]\n"
        last_fam = fam
        tex += f"{famtxt} & {METHOD_NAME[m]} & " + " & ".join(cell(c, m, 10) for c in COHORTS) + " \\\\\n"
    tex += "\\midrule\n"
    for m, k in [("ihc_2", 2), ("ihc_4", 4), ("panel_girard2016", 42), ("panel_wilkerson2013", 52)]:
        label = METHOD_NAME[m] + f" ($k = {k}$)"
        tex += f"Reference & {label} & " + " & ".join(cell(c, m, k) for c in COHORTS) + " \\\\\n"
    tex += "Reference & random-$k$ ($k = 10$) & " + " & ".join(cell(c, "random_k", 10) for c in COHORTS) + " \\\\\n"
    b0cells = []
    for c in COHORTS:
        b0cells.append(b0.loc[c, "AUROC"].replace("±", "$\\pm$"))
        log("tab:e1_k10", f"{c}/b0", "AUROC", b0.loc[c, "AUROC"], "e1_b0_table.csv", "AUROC")
    tex += "Reference & B0 (all genes of $G$) & " + " & ".join(b0cells) + " \\\\\n"
    tex += "\\midrule\n"
    wins = []
    for c in COHORTS:
        g = t[(t.k == 10) & (t.cohort == c) & (t.method.isin(DATA_METHODS))]
        wins.append(f"{int(g.beats_random_holm.sum())}/{len(g)}")
        log("tab:e1_k10", f"{c}/wins_k10", "beats_random_holm", f"{int(g.beats_random_holm.sum())}/{len(g)}", "e1_tests_vs_random_b0.csv", "beats_random_holm, k = 10")
    tex += "\\multicolumn{2}{l}{Methods above random-$k$ at $k = 10$ (Holm)} & " + " & ".join(wins) + " \\\\\n"
    tex += r"""\bottomrule
\end{tabular}
\end{adjustbox}
\end{table*}
"""
    write(os.path.join(out, "tab_e1_k10.tex"), tex)

    # wins by k (used in text)
    for k in [1, 2, 3, 4, 5, 10, 25, 50]:
        for c in COHORTS:
            g = t[(t.k == k) & (t.cohort == c) & (t.method.isin(DATA_METHODS))]
            log("text:e1_wins", f"{c}/k={k}", "beats_random_holm", f"{int(g.beats_random_holm.sum())}/{len(g)}", "e1_tests_vs_random_b0.csv", "beats_random_holm")
    below = t[t.differs_from_b0_holm == True]
    for _, r in below.iterrows():
        log("text:e1_below_b0", f"{r.cohort}/{r.method}/k={r.k}", "diff_vs_b0,p_holm", f"{r.diff_vs_b0:+.3f} (p_Holm {r.p_nb_b0_holm:.3f})", "e1_tests_vs_random_b0.csv", "differs_from_b0_holm")
    # log-loss and Brier at k = 10 (text)
    for c in COHORTS:
        g = s[(s.cohort == c) & (s.k == 10)]
        vals = {m: (round(float(r.logloss_mean), 3), round(float(r.brier_mean), 3)) for m, r in g.set_index("method").iterrows()}
        log("text:e1_logloss_k10", c, "logloss,brier by method", str(vals), "e1_summary.csv", "logloss_mean, brier_mean, k = 10")
        log("text:e1_logloss_k10", f"{c}/b0", "logloss,brier", f"{b0.loc[c, 'logloss_mean']:.3f},{b0.loc[c, 'brier_mean']:.3f}", "e1_b0_table.csv", "logloss_mean, brier_mean")
    # secondary classifiers
    s_all = rd(results, "e1_summary.csv")
    lr = s_all[(s_all.classifier == "lr_l2") & (s_all.k.isin([5, 25]))].set_index(key).auroc_mean
    for clf in ["rf", "svm_linear"]:
        o = s_all[s_all.classifier == clf].set_index(key).auroc_mean
        d = (o - lr.reindex(o.index)).dropna()
        log("text:e1_secondary", clf, "mean diff vs lr_l2", round(float(d.mean()), 3), "e1_summary.csv", "classifier = rf / svm_linear, k in {5, 25}")
        log("text:e1_secondary", clf, "max |diff| vs lr_l2", round(float(d.abs().max()), 3), "e1_summary.csv", str(d.abs().idxmax()))


