def tab_app_e1(results, out):
    a = rd(results, "e1_auroc_table.csv")
    ks = ["1", "2", "3", "4", "5", "10", "25", "50"]
    for c in COHORTS:
        g = a[a.cohort == c].set_index("method")
        tex = header("e1_auroc_table.csv (cells = mean +- SD of AUROC over repeated patient-level CV)")
        tex += "\\begin{table*}[p]\n\\centering\n\\scriptsize\n"
        tex += (f"\\caption{{E1 on {COHORT_NAME[c]}: AUROC (mean $\\pm$ SD, LR-L2) by method and budget $k$. "
                "$k$-TSP exists for even $k$ only; wrappers at $k \\in \\{5, 10, 50\\}$ on the GPL570 cohorts; "
                "knowledge panels at their own size (IHC-2: $k = 2$, IHC-4: $k = 4$, Girard 2016: 42 genes, Wilkerson 2013: 52 genes; the number of genes present on each platform is given in Section~\\ref{sec:framework}).}\n")
        tex += f"\\label{{tab:app_e1_{c.split('_')[0]}}}\n\\setlength{{\\tabcolsep}}{{3pt}}\n\\renewcommand{{\\arraystretch}}{{1.1}}\n"
        tex += "\\begin{adjustbox}{max width=\\textwidth,max totalheight=0.86\\textheight}\n\\begin{tabular}{ll" + "c" * len(ks) + "}\n\\toprule\n"
        tex += "\\textbf{Family} & \\textbf{Method} & " + " & ".join(f"$k={k}$" for k in ks) + " \\\\\n\\midrule\n"
        last = None
        for m in DATA_METHODS + ["ihc_2", "ihc_4", "panel_girard2016", "panel_wilkerson2013", "random_k"]:
            if m not in g.index:
                continue
            fam = FAMILY.get(m, "Reference")
            famtxt = fam if fam != last else ""
            if fam != last and last is not None:
                tex += "\\addlinespace[2pt]\n"
            last = fam
            cells = []
            for k in ks:
                v = g.loc[m, k]
                if m == "panel_girard2016":
                    v = g.loc[m, "42"] if k == "50" else ""
                if m == "panel_wilkerson2013":
                    v = g.loc[m, "52"] if k == "50" else ""
                v = "" if (isinstance(v, float) and math.isnan(v)) else str(v)
                cells.append(v.replace("±", "$\\pm$") if v else "--")
                if v:
                    log(f"tab:app_e1_{c}", f"{m}/k={k}", "auroc", v, "e1_auroc_table.csv", f"column {k}")
            name = METHOD_NAME[m]
            if m == "panel_girard2016":
                name += " (42 genes)"
            if m == "panel_wilkerson2013":
                name += " (52 genes)"
            tex += f"{famtxt} & {name} & " + " & ".join(cells) + " \\\\\n"
        tex += "\\bottomrule\n\\end{tabular}\n\\end{adjustbox}\n\\end{table*}\n"
        write(os.path.join(out, f"tab_app_e1_{c.split('_')[0]}.tex"), tex)


