def log(table, row, col, value, src, key):
    LOG.append({"table": table, "row": str(row), "col": str(col), "value": value,
                "source": src, "key": str(key)})


def f3(x):
    return "" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.3f}"


def fsd(m, s):
    if m is None or (isinstance(m, float) and math.isnan(m)):
        return "--"
    return f"{m:.3f} $\\pm$ {s:.3f}"


def fsigned(x, nd=3):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    return f"{x:+.{nd}f}"


def ftime(x):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    if x >= 100:
        return f"{x:.0f}"
    if x >= 10:
        return f"{x:.1f}"
    if x >= 1:
        return f"{x:.2f}"
    return f"{x:.3f}"


def fp(p):
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "--"
    if p < 0.001:
        return "$<$0.001"
    return f"{p:.3f}"


def tex_escape(s):
    return str(s).replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def header(src, note=""):
    return (f"% source: {src}\n% generated by Scripts/make_tables.py from tables_official_2026-11-03 "
            f"(commit e15fb7c, label [v03-11]); do not edit by hand.\n" + (f"% {note}\n" if note else ""))


def write(path, text):
    Path(path).write_text(text, encoding="utf-8")
    print("wrote", path)


def rd(results, name):
    return pd.read_csv(os.path.join(results, name), encoding="utf-8-sig")


