def tab_datasets(e0_cfg_dir, qc_dir, results, out):
    e0 = rd(results, "e0_signal_check.csv").set_index("cohort")
    cross = pd.read_csv(os.path.join(qc_dir, "label_crosscheck_summary.csv")).set_index("cohort")
    rows = []
    info = {
        "tcga_luad_lusc_primary_tumor": ("TCGA-LUAD / TCGA-LUSC (GDC, STAR counts)", "RNA-seq, $\\log_2(\\mathrm{TPM}+1)$", "source ($D_S$); reference cohort with large $n$"),
        "gse10245": ("GSE10245", "Affymetrix HG-U133 Plus 2.0 (GPL570), gcRMA", "small target; $n_T \\in \\{5, 10\\}$ only"),
        "gse30219": ("GSE30219 (release R5)", "GPL570, RMA", "target"),
        "gse37745": ("GSE37745", "GPL570, RMA", "target; E4--E5 stability cohort"),
        "gse42127": ("GSE42127", "Illumina HumanWG-6 v3 (GPL6884), MBCB", "second platform; reported separately"),
    }
    for c in COHORTS:
        cfg = json.load(open(os.path.join(e0_cfg_dir, c, "config.json")))
        n0, n1 = cfg["gene_space"]["n_per_class"]
        n = int(e0.loc[c, "n"]); p = int(e0.loc[c, "p"])
        assert n == n0 + n1, (c, n, n0, n1)
        p_native = cfg["gene_space"].get("n_genes_before_gene_space", p)
        excl = int(cross.loc[c, "n_excluded_qc"]) if c in cross.index else 2  # TCGA: sex_check_summary n_quarantine = 2
        name, platform, role = info[c]
        rows.append((name, platform, f"{n:,}", f"{n0}/{n1}", f"{excl}", f"{p_native:,}", f"{p:,}", role))
        log("tab:datasets", c, "n", n, "e0_signal_check.csv", "n")
        log("tab:datasets", c, "n_per_class", f"{n0}/{n1}", f"E0/{c}/config.json", "gene_space.n_per_class")
        log("tab:datasets", c, "p_native", p_native, f"E0/{c}/config.json", "gene_space.n_genes_before_gene_space")
        log("tab:datasets", c, "p_G", p, "e0_signal_check.csv", "p")
        log("tab:datasets", c, "excluded_qc", excl, "qc/label_crosscheck_summary.csv or qc/sex_check_summary.csv", "n_excluded_qc / n_quarantine")
    tex = header("e0_signal_check.csv (n, p); E0/<cohort>/config.json (gene_space.n_per_class, n_genes_before_gene_space); qc/label_crosscheck_summary.csv (n_excluded_qc); qc/sex_check_summary.csv (TCGA n_quarantine)")
    tex += r"""\begin{table*}[t]
\centering
\scriptsize
\caption{Cohorts after quality control. $n$ = patients retained (one sample per patient); LUAD/LUSC = class sizes (LUSC is the positive class); Excl. = samples removed by the expression-based sex check and duplicate screen; $p$ (native) = genes measured on the platform; $|G|$ = genes in the common space with the TCGA source, which is the gene space used by every selector. The TCGA count includes two quarantined samples removed by the same sex check.}
\label{tab:datasets}
\setlength{\tabcolsep}{4pt}
\renewcommand{\arraystretch}{1.15}
\begin{adjustbox}{max width=\textwidth}
\begin{tabular}{llrrrrrl}
\toprule
\textbf{Cohort} & \textbf{Platform / normalisation} & $\boldsymbol{n}$ & \textbf{LUAD/LUSC} & \textbf{Excl.} & $\boldsymbol{p}$ \textbf{(native)} & $\boldsymbol{|G|}$ & \textbf{Role in the benchmark} \\
\midrule
"""
    for r in rows:
        tex += " & ".join(r) + " \\\\\n"
    tex += r"""\bottomrule
\end{tabular}
\end{adjustbox}
\end{table*}
"""
    write(os.path.join(out, "tab_datasets.tex"), tex)


